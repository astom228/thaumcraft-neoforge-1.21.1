"""Сводка фактически полученных отчётов. Запуск после серверных и разрешённого клиентского прогона."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
def read(path):
    return json.loads((root / path).read_text(encoding="utf-8-sig"))

client = read("build/client-performance.json")
rows = []
for profile, title in [("vanilla", "Thaumcraft + Curios/TerraBlender"), ("botania", "Также Create/JEI/Botania/Patchouli")]:
    for phase, label in [("create", "создание"), ("reload", "повторная загрузка")]:
        report = read(f"build/stability-{profile}/report-{phase}.json")
        assert (root / f"build/stability-{profile}/saved-{phase}.ok").exists()
        rows.append(f"| {title}, {label} | {report['samples']} | {report['mspt_mean']:.3f} | {report['mspt_p95']:.3f} | {report['mspt_p99']:.3f} | {report['mspt_max']:.3f} | {report['ticks_over_50ms']} |")

frames = []
for key, title in [("baseline", "Обычная сцена"), ("particle_load", "Стресс частиц"), ("recovery", "После снятия нагрузки")]:
    data = client[key]
    assert data["frames"] > 100
    frames.append(f"| {title} | {data['frames']} | {data['mean_fps']:.1f} | {data['p95_ms']:.2f} | {data['p99_ms']:.2f} | {data['max_ms']:.2f} | {data['frames_over_50ms']} |")

